import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const files = new Map();
async function visit(name) {
  if (files.has(name)) return;
  const content = await readFile(path.join(root, name));
  files.set(name, content);
  const text = content.toString();
  const dependencies = [];
  if (name.endsWith('.html')) {
    for (const match of text.matchAll(/(?:src|href)=["']([^"']+)["']/g)) if (match[1] !== './') dependencies.push(match[1]);
  } else if (name.endsWith('.js')) {
    for (const match of text.matchAll(/^\s*(?:import|export)\s+(?:[^;\n]*?\sfrom\s*)?["']([^"']+)["']/gm)) dependencies.push(match[1]);
    for (const match of text.matchAll(/new URL\(["']([^"']+)["'],\s*import\.meta\.url\)/g)) dependencies.push(match[1]);
  } else if (name.endsWith('.css')) {
    for (const match of text.matchAll(/url\(\s*["']?([^\s)'" ]+)/g)) dependencies.push(match[1]);
  }
  for (const dependency of dependencies) {
    if (dependency.startsWith('#') || dependency.startsWith('data:')) continue;
    if (!dependency.startsWith('.')) throw new Error(`Recurso no relativo: ${name}: ${dependency}`);
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(name), dependency));
    if (resolved.startsWith('../')) throw new Error('Recurso fuera del proyecto');
    // The service worker and its generated inventory are installed by the browser.
    if (resolved === 'sw.js') continue;
    await visit(resolved);
  }
}
await visit('index.html');
const assets = [...files].sort(([a],[b]) => a.localeCompare(b)).map(([name, bytes]) => ({
  path: `./${name}`, integrity: `sha256-${createHash('sha256').update(bytes).digest('base64')}`,
}));
const version = createHash('sha256').update(JSON.stringify(assets)).digest('hex').slice(0, 20);
const output = `// Generated by npm run build:cache. Do not edit manually.\nself.PRECACHE = ${JSON.stringify({version, assets}, null, 2)};\n`;
const destination = path.join(root, 'sw-assets.js');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('Inventario desactualizado. Ejecuta npm run build:cache antes de publicar.');
} else {
  await writeFile(destination, output);
  console.log(`${assets.length} archivos preparados para caché (${version}).`);
}
